def calculate_solar_generation(
    irradiance_wh_m2,
    pv_capacity_kw,
    system_efficiency,
):
    """
    Estimate hourly electricity generated by a PV system.

    Parameters
    ----------
    irradiance_wh_m2 : float
        Hourly solar irradiance from NASA POWER in Wh/m².

    pv_capacity_kw : float
        Rated capacity of the PV array in kW.

    system_efficiency : float
        Fraction of generated energy remaining after system losses.

    Returns
    -------
    float
        Estimated electricity generation in kWh for the hour.
    """
    irradiance_factor = irradiance_wh_m2 / 1000
    generation_kwh = pv_capacity_kw * irradiance_factor * system_efficiency
    return generation_kwh
